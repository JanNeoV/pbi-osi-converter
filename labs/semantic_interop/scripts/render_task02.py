"""Generate researcher tables from a sealed diagnostic report, never from hand-entered counts."""
import argparse
from collections import Counter
import json
from pathlib import Path

from semantic_lab.fixtures import LAB


def render(report, relative_evidence):
    diagnostics = report["semantic_diagnostics"]
    variants = [("Pinned", diagnostics["summary"])] + [
        (name.title(), item["summary"]) for name,item in diagnostics.get("comparisons", {}).items()]
    text = ["# Differential evaluation", "", "Generated by `scripts/render_task02.py` from [sealed evidence](" + relative_evidence + ").",
            "A row describes query cases within one environment and intervention lane. Do not aggregate these into a converter pass rate.", "",
            "| Environment | Lane | Cases | Executed | Match oracle | Status counts |", "|---|---|---:|---:|---:|---|"]
    for label, summary in variants:
        for lane in ("native", "roundtrip", "level3_spine", "level3_legacy_spine", "level3_spine_defaults"):
            s = summary[lane]
            text.append(f"| {label} | {lane} | {s['cases']} | {s['executed']} | {s['matching_oracle']} | {json.dumps(s['statuses'], sort_keys=True)} |")
    text += ["", "Level 1 is `roundtrip`. Every `level3_*` lane explicitly reconstructs source configuration. "
             "Repair uses the separately recorded converter patch **and** Level 3 reconstruction. Its PASS values are bounded query-contract passes, not lossless conversion claims.",
             "", "## Per-metric definition matrix", "", "| Metric | Definition classification | Native query cases | Repair executed / attempted | Repair matches |", "|---|---|---:|---:|---:|"]
    repair_report = report.get("_repair_report", {})
    for f in diagnostics["findings"]:
        if not f["id"].startswith("metric.") or not f["id"].endswith(".definition"):
            continue
        metric = f["id"].split(".")[1]
        source = [c for c in report["cases"] if c["metric_id"] == metric and c["path"] == "native"]
        cases = [c for c in repair_report.get("cases", []) if c["metric_id"] == metric and c["path"] == "level3_spine_defaults"]
        executed = sum(c["execution_status"] == "EXECUTED" for c in cases)
        matches = sum(bool(c["comparison"] and c["comparison"]["equal"]) for c in cases)
        text.append(f"| {metric} | {f['classification']} | {len(source)} | {executed} / {len(cases)} | {matches} |")
    text += ["", "Definition preservation is narrower than model preservation: all pinned/current round-trip queries remain blocked.",
             "", "## Diagnostic inventory", "", "| Classification | Attribute observations |", "|---|---:|"]
    for category, count in sorted(Counter(f["classification"] for f in diagnostics["findings"]).items()):
        text.append(f"| {category} | {count} |")
    text += ["", "These are observations, not independent defects; UNKNOWN includes unexercised metadata and temporal behavior.",
             "", "## Controlled failures", ""]
    controls = [r for r in report["cases"] if r["controlled_failure"]]
    text.append(f"Detected {sum(c['failure_detection'] == 'DETECTED' for c in controls)} / {len(controls)}; "
                f"numerical mismatches {sum(c['status'] == 'NUMERICAL_MISMATCH' for c in controls)}. These remain deliberate mutations.")
    text += ["", "## Microsoft measures", "", "| Metric | Emitted DAX | Classification |", "|---|---|---|"]
    for row in diagnostics["microsoft"]["matrix"]:
        text.append(f"| {row['metric']} | `{row['dax']}` | {row['classification']} |")
    text += ["", "All Microsoft runtime outcomes are NOT_EXECUTED. Warnings, annotations, original expressions and endpoints are in the evidence.", ""]
    return "\n".join(text)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("report", type=Path)
    parser.add_argument("--output", type=Path, default=LAB / "docs/DIFFERENTIAL_EVALUATION.md")
    args = parser.parse_args()
    report = json.loads(args.report.read_text())
    repair = args.report.parent / "repair/report.json"
    if repair.exists():
        report["_repair_report"] = json.loads(repair.read_text())
    import os
    link = Path(os.path.relpath(args.report.resolve(), args.output.resolve().parent)).as_posix()
    args.output.write_text(render(report, link), encoding="utf-8")
    print(args.output)


if __name__ == "__main__":
    main()
